const COPY: Record<'en' | 'si' | 'ta', Copy> = { en, si, ta };

export type ContributeCopy = Copy;

export const fill = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (_, key) => (values[key] !== undefined ? String(values[key]) : `{${key}}`));

export const useContributeCopy = () => {
  const { language } = useLanguage();
  return { t: COPY[language] || en, language };
};

/** Picks the name in the active language, falling back to English. */
export const localName = (
  item: { name_en?: string | null; name_si?: string | null; name_ta?: string | null; nameEn?: string; nameSi?: string; nameTa?: string } | null | undefined,
  language: 'en' | 'si' | 'ta',
): string => {
  if (!item) return '';
  const en = item.name_en ?? item.nameEn ?? '';
  const si = item.name_si ?? item.nameSi ?? '';
  const ta = item.name_ta ?? item.nameTa ?? '';
  if (language === 'si' && si.trim() && si.trim() !== en.trim()) return si;
  if (language === 'ta' && ta.trim() && ta.trim() !== en.trim()) return ta;
  return en || si || ta;
};
